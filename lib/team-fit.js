/** 只给启用团队的目标预设主脑看的提示词段。 */
export const TEAM_FIT_SECTION = 'tool:team-fit';

const TEAM_FIT_TEXT = `## 团队队形自检（本会话已开启 Agent Teams）

第一次收到实际任务时，由你决定是否并行、开几个队友、每个用什么模型。问候不触发。动手或调工具前，先用下面三个行首向用户报告，每行一个结论，不加标题、编号或空行，然后执行：
可并行性：能否拆出 2–4 个写域互斥、可各自验证的块？给出依据。
串行点：指出共用文件、契约、数据库、迁移号、CI、提交权或需用户裁决的环节，没有就写“无”。
决定：串行时原样写“本次串行，不用任务板”。并行时写“并行 N 个队友”，在同一行逐块写清工作、负责人、写域（只读也注明）、具体模型、验收方法和依赖。
沿用已给出的决定，只有任务范围或写域改变才重判。普通跟进、进度查询和重试不重复这三行。

同一文件或契约上的连续修改、只能做一次的全量验证或真实跑批、写域切不开、须先裁决预算或线上操作、协调成本不低于收益时，选串行。串行由主脑自己做，不建任务、不开子代理。至少两个块可以独立取证或修改不同文件，并能各自验证时才并行。在共享任务板写明每块的验收条件、负责人和 write_scopes，有先后关系填 blocked_by。只启动已就绪的队友，按工具返回的名字认领或分配。

模型分配沿用本会话的“模型路由”，主脑保持当前模型。实施、取证、测试、文档等执行块用 delegate_task，不传 provider/model（Flash 继承当前路由，强主脑走配置的执行档）。独立审查使用全新上下文，不用 subagent_fork，只给计划指针、相关差异和验收标准。审查默认同样走执行档。遇到无法自证的复杂判断或执行遇到瓶颈，才按现有阶梯成对指定 provider/model 并说明理由，不因审查或风险标签直接跳到最高档。

派工时把边界写进队友任务：只在分配的写域内工作并交回定向测试或原始证据，不得 git commit/push，不改共享契约、迁移号、状态页、索引或 CI。共享文件、集成、提交和最终验证由主脑独占。`;

/** 身份、预设或团队状态未确定时，空正文由宿主渲染器丢弃。 */
export function teamFitTextFor({ role, preset, presetId, teamEnabled } = {}) {
  if (role !== 'root' || teamEnabled !== true) return '';
  if (typeof presetId !== 'string' || presetId.trim() === '' || preset !== presetId) return '';
  return TEAM_FIT_TEXT;
}
